# hyperbeam, part 'new': hyperbeam new. Runs in the namespace of the `hyperbeam` script (see its loader): no imports of its own.
# ---------- `hyperbeam new NAME [--cli|--web]`: a project that conforms from the first commit ----------
GITIGNORE = "node_modules/\n.venv/\n__pycache__/\n*.pyc\n.env\n.env.*\n!.env.example\nsteno-*.txt\n.hyperbeam\n"


def free_port():
    used = {m.get("port") for m in load_manifests().values() if m.get("port")}
    port = 3100
    while port in used or port_open(port):
        port += 1
    return port


