def show_session(sess):
    """Show a session. Sidebar menu: switch the sidebar's right client. Otherwise switch the client that is looking at the menu session
    (switch mode, and over SSH), or in window mode at the laptop open a new kitty window. Returns what it did."""
    if os.environ.get("HB_SIDEBAR"):
        c = sidebar_client()
        if not c:                                           # the right split was closed: open it again in this window
            kitten_sidebar("launch", "--location=vsplit", "--title", "main", "hyperbeam", "_right", check=False)
            for _ in range(20):
                time.sleep(0.25)
                c = sidebar_client()
                if c:
                    break
        if not c:
            raise RuntimeError("the sidebar's main area is not attached (close this window and press the hotkey again)")
        tmux("switch-client", "-c", c, "-t", home_target(c) if sess == MENU else f"={sess}")
        return "switched the main area"
    pid = menu_client("client_pid")
    if not pid:
        raise RuntimeError("no client is attached to the menu session")
    if open_mode() == "window" and not client_is_remote(pid):
        spawn_kitty(sess)
        return "new kitty window"
    c = menu_client()
    tmux("switch-client", "-c", c, "-t", home_target(c) if sess == MENU else f"={sess}")
    return "switched"


def source_conf():
    """Load hyperbeam.conf into the running tmux server (tmux.conf also sources it at server start)."""
